export default function (eleventyConfig) {
  // content/, data/ and admin/ are copied VERBATIM — they are the same
  // files the old site used, and Decap CMS keeps writing to content/news/.
  for (const dir of ["content", "data", "admin", "static"]) {
    eleventyConfig.addPassthroughCopy(dir);
  }
  // 3d/ = the DELTA-Hub 3D Experience (static app, no build step), served at /3d/
  eleventyConfig.addPassthroughCopy("3d");
  eleventyConfig.addPassthroughCopy("CNAME");
  eleventyConfig.addPassthroughCopy(".nojekyll");

  // Render a markdown string
  eleventyConfig.addFilter("md", (s) => md.render(s || ""));

  // Render a markdown FILE from the project root (replaces the old
  // client-side data-markdown="..." loader — same files, rendered at build)
  eleventyConfig.addFilter("mdfile", (p) => {
    const file = path.join(process.cwd(), p);
    if (!fs.existsSync(file)) return "";
    const { content } = matter(fs.readFileSync(file, "utf8"));
    return md.render(content);
  });

  // "June 25, 2026" — same format the old site produced in English browsers
  eleventyConfig.addFilter("niceDate", (d) => {
    if (!d) return "";
    const date = d instanceof Date ? d : new Date(d);
    if (isNaN(date)) return String(d);
    return date.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });
  });

  // ISO date (YYYY-MM-DD), used where the old site printed raw dates
  eleventyConfig.addFilter("isoDate", (d) => {
    if (!d) return "";
    const date = d instanceof Date ? d : new Date(d);
    if (isNaN(date)) return String(d);
    return date.toISOString().split("T")[0];
  });

  eleventyConfig.addFilter("rebase", (html, root) => {
    if (!root) return html;
    return html.replace(/(src|href|poster)="(?!https?:|mailto:|#|\/|\.\.?\/)/g, `$1="${root}`);
  });

  eleventyConfig.addShortcode("icon", (name, cls = "icon") => {
    if (STROKE_ICONS[name]) {
      return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${STROKE_ICONS[name]}</svg>`;
    }
    if (BRAND_ICONS[name]) {
      return `<svg class="${cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${BRAND_ICONS[name]}</svg>`;
    }
    return "";
  });

  return {
    dir: { input: "src", includes: "_includes", data: "_data", output: "_site" },
    htmlTemplateEngine: "njk",
    markdownTemplateEngine: "njk",
  };
}
